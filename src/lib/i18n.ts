export function t(key: string, vars?: Record<string, string | number>): string {
  let str = en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replaceAll(`{${k}}`, String(v));
    });
  }
  return str;
}

export function useLanguage(): { t: typeof t } {
  return { t };
}
